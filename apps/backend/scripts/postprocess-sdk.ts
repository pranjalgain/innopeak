// Post-processing for the generated axios client SDK (run by `generate:sdk`, itself run by
// `generate:client` / the root `pnpm generate:sdk`).
// These steps aren't expressible in sdk-config.axios.json (the OpenAPI generator has
// no option for them), so we apply them here after generation:
// 1. Repoint package.json at the TS source (we consume source, no build step), and pin its axios
//    dependency to the exact version every other package in this monorepo uses. The generator
//    template always declares a `^` range against whatever axios version it shipped with — left
//    alone, pnpm resolves that range independently and installs a SECOND axios copy alongside the
//    one apps/web depends on. Two copies means two structurally-identical-but-nominally-different
//    `axios` modules from TypeScript's point of view, which silently breaks the `declare module
//    "axios"` augmentation apps/web's api-sdk layer uses to add `authOptional`/`skipRefresh` to
//    `AxiosRequestConfig` — the augmentation lands on one copy, the SDK's own types resolve against
//    the other, and every call site that passes those custom fields fails to compile.
// 2. Strip the generator's header banner from every file. The generator templates
//    the API title + description + version into the JSDoc banner of *every* file, so
//    a one-word edit to the Swagger description (DocumentBuilder.setDescription/Title/
//    Version in bootstrap.ts) would otherwise churn a comment in all ~100 SDK files. The SDK
//    is `@ts-nocheck` and never hand-read, so the banner is dead weight — dropping it
//    keeps regen diffs limited to files whose actual shape changed.
// 3. Prepend `// @ts-nocheck` to every generated file — the SDK is always
//    auto-generated and never hand-edited, so we don't type-check/lint it
//    (avoids the generator's unused-import errors leaking into app builds).
import * as fs from 'node:fs';
import * as path from 'node:path';

const sdkDir = path.resolve(__dirname, '../../../libs/client_sdk');

// Kept in lockstep with apps/web's own pinned axios version (and the root/apps/documentation
// packages, which already match) — see the note above for why these must never diverge.
const AXIOS_VERSION = '1.12.2';

// The volatile header banner — the first JSDoc block, identified unambiguously by the
// generator's "auto generated by OpenAPI Generator" marker (present in every file).
const GENERATOR_BANNER = /\/\*\*[\s\S]*?auto generated by OpenAPI Generator[\s\S]*?\*\/\n?/;

// 1. Trim package.json, point entry fields at the source files, and pin axios.
const pkgPath = path.join(sdkDir, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
pkg.main = './index.ts';
pkg.module = './index.ts';
pkg.typings = './index.ts';
pkg.dependencies = { ...pkg.dependencies, axios: AXIOS_VERSION };
delete pkg.scripts;
delete pkg.devDependencies;
fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

// 2 + 3. Strip the generator banner, then ensure a leading `// @ts-nocheck`.
function processFile(dir: string): void {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) processFile(full);
    else if (full.endsWith('.ts')) {
      let content = fs.readFileSync(full, 'utf8');
      content = content.replace(GENERATOR_BANNER, '');
      if (!content.startsWith('// @ts-nocheck')) {
        content = `// @ts-nocheck\n${content}`;
      }
      fs.writeFileSync(full, content);
    }
  }
}
processFile(sdkDir);
